            f1 = f"ما هي الرؤية المشتركة التي سنتفق عليها لإدارة {desc} بنجاح يمنع أي ضغط أو إرهاق نفسي؟"
            q2 = f"لو واجهنا موقفاً معقداً أو خلافاً في وجهات النظر بخصوص {topic}، كيف سنصل لحل منصف يرضي الطرفين؟"
            f2 = f"هل الاحتكام للشفافية المطلقة ولغة الحوار الهادئ في {desc} هو أفضل وسيلة لتجاوز أي عقبة؟"
            q3 = f"إيه رأيك لو اتفقنا على خطة عملية واضحة تخص {topic} ونراجعها معاً كل فترة برضا تام؟"
