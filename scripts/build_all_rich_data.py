            f2 = f"هل الحوار البسيط والمرح حول {desc} بيضفي بهجة وألفة على تفاصيل بيتنا الصغير؟"
            q3 = f"إيه رأيك لو حطينا عادة أسبوعية جميلة تخص {topic} نستمتع بيها ونكسر بيها الروتين؟"
            f3 = f"كيف يساعد الاتفاق الهادئ على {desc} في توفير وقتنا وطاقتنا لأوقات القرب والمودة؟"
            q4 = f"إيه اللفتة أو التصرف اللي لو قمت بيه بخصوص {topic} يسعدك وتحس باهتمامي بتفاصيلك؟"
