            q2 = f"لو تعرض بيتنا لظرف قاهر ومفاجئ يخص {topic}، كيف سنقف معاً كالطود الأشم دون أن تهتز ثقتنا؟"
            f2 = f"ما هو العهد الصارم بألا نجعل من تحديات الدنيا في {desc} سبباً في أي شرخ لعاطفتنا ومودتنا؟"
