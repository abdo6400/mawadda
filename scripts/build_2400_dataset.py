def generate_all_questions():
    all_questions = []
    seen_q_texts = set()
    seen_f_texts = set()
    seen_ids = set()

    for cat in CATEGORIES:
        cat_id = cat["id"]
        spec = DATA_SPECS[cat_id]
        prefix = spec["prefix"]

        levels_data = [
            (1, spec["l1"], L1_ANGLES),
            (2, spec["l2"], L2_ANGLES),
            (3, spec["l3"], L3_ANGLES)
        ]

        for level, subjects, angles in levels_data:
            q_count = 0
            for s_idx, (s_name, s_desc, s_tags) in enumerate(subjects):
                for a_idx, (q_tpl, f_tpl) in enumerate(angles):
                    q_count += 1
                    qid = f"{prefix}_l{level}_{str(q_count).zfill(3)}"
                    q_text = q_tpl.format(subj=s_name, desc=s_desc)
                    f_text = f_tpl.format(subj=s_name, desc=s_desc)

                    # Check uniqueness
                    if q_text in seen_q_texts:
                        print(f"ERROR: Duplicate question text: {q_text}")
                        sys.exit(1)
                    if f_text in seen_f_texts:
                        print(f"ERROR: Duplicate follow-up text: {f_text}")
                        sys.exit(1)
                    if qid in seen_ids:
                        print(f"ERROR: Duplicate ID: {qid}")
                        sys.exit(1)

                    seen_q_texts.add(q_text)
                    seen_f_texts.add(f_text)
                    seen_ids.add(qid)

                    all_questions.append({
                        "id": qid,
                        "categoryId": cat_id,
                        "level": level,
                        "question": q_text,
                        "followUp": f_text,
                        "tags": s_tags
                    })

    return all_questions

