const allData = {
  version: "1.0.0",
  lastUpdated: new Date().toISOString().split('T')[0],
  totalQuestions: 180,
  categories: categories,
  questions: []
};

function processQuestions(list, categoryId, prefix) {
  list.forEach((item, index) => {
    const num = (index % 10) + 1;
    const padded = String(num).padStart(2, '0');
    const id = `${prefix}_${item.level}_${padded}`;
    allData.questions.push({
      id: id,
      categoryId: categoryId,
      level: item.level,
      question: item.question.trim(),
      followUp: item.followUp.trim(),
      tags: item.tags
    });
  });
}

